"""Generate web/app/patches.js for Persona 5 Royal 4:3 without requiring the 395MB original exe.
Uses the committed PE header in tools/p5r_pe_hdr.bin and known original SHA-256.
"""
import hashlib
import json
import os
import struct
import sys

ORIGINAL_SIZE = 395876288
ORIGINAL_SHA256 = '5d9e18c383700302d029c947ddf8c811ba6afa47e60ec1afa0554d452bdc0cbf'
DEFAULT_SETS = ['fit43', 'cam43', 'film43']

# import patch logic from p5r_patch
sys.path.insert(0, os.path.join(os.path.dirname(__file__)))
from p5r_patch import sections, rva2off, build


def generate(out_path, names=None):
    if names is None:
        names = DEFAULT_SETS
    hdr_path = os.path.join(os.path.dirname(__file__), 'p5r_pe_hdr.bin')
    hdr = open(hdr_path, 'rb').read()
    secs = sections(hdr)

    out = []
    for p in build(names):
        if p[1] == 'RAW':
            out.append((p[0], p[2], p[3], p[4]))
        else:
            out.append((p[0], rva2off(secs, p[1]), p[2], p[3]))
    resolved = sorted(out, key=lambda x: x[1])

    tab = {
        'size': ORIGINAL_SIZE,
        'sha256': ORIGINAL_SHA256,
        'sets': names,
        'patches': [{'name': n, 'offset': o, 'old': ob.hex(), 'new': nb.hex()} for n, o, ob, nb in resolved]
    }
    content = '/* generated by tools/gen_web_data.py; do not edit */\nglobalThis.P5R_PATCHES = ' + json.dumps(tab, indent=1) + ';\n'
    open(out_path, 'w').write(content)
    print(f'[+] wrote {len(tab["patches"])} patches to {out_path}')


if __name__ == '__main__':
    out_file = sys.argv[1] if len(sys.argv) > 1 else 'web/app/patches.js'
    generate(out_file)
